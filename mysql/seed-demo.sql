UPDATE `product_sku` s
JOIN `product` p ON p.id = s.product_id
JOIN (
    SELECT a.id, COUNT(b.id) + 1 AS seq
    FROM `product_sku` a
    LEFT JOIN `product_sku` b ON b.product_id = a.product_id AND b.id < a.id
    GROUP BY a.id
) t ON t.id = s.id
SET s.sku_code = CONCAT(p.product_code, '-', t.seq);

